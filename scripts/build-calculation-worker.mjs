import {build} from 'esbuild';
import {mkdir,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
await mkdir(new URL('src/generated/',root),{recursive:true});
const browser=await build({entryPoints:[new URL('src/workers/calculation-entry.ts',root).pathname],bundle:true,write:false,format:'iife',platform:'browser',target:'es2022',minify:true,define:{'process.env.NODE_ENV':'"production"'},logLevel:'warning'});
await writeFile(new URL('src/generated/calculation-worker-source.ts',root),`// Generated by scripts/build-calculation-worker.mjs; do not edit.\nexport const CALCULATION_WORKER_SOURCE: string = ${JSON.stringify(browser.outputFiles[0].text)};\n`);
console.log(`Prepared self-contained calculation worker (${browser.outputFiles[0].contents.length} bytes).`);
