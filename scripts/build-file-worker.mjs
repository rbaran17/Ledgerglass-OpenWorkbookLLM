import { build } from "esbuild";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import ts from "typescript";
const root = new URL("../", import.meta.url),
  literals = new Set(),
  templates = [];
// Only complete build-time string literals can be echoed as public file errors.
async function scan(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.name === "generated") continue;
    const path = new URL(e.name + (e.isDirectory() ? "/" : ""), dir);
    if (e.isDirectory()) await scan(path);
    else if (/\.tsx?$/.test(e.name)) {
      const source = ts.createSourceFile(
        e.name,
        await readFile(path, "utf8"),
        ts.ScriptTarget.Latest,
        true,
      );
      function visit(n) {
        if (
          (ts.isNewExpression(n) || ts.isCallExpression(n)) &&
          /^(?:Error|TypeError|RangeError|fail|invalid|refuse|issue|string|integer|boundedString)$/.test(
            n.expression.getText(source),
          )
        )
          for (const arg of n.arguments ?? []) {
            if (
              ts.isStringLiteral(arg) ||
              ts.isNoSubstitutionTemplateLiteral(arg)
            )
              literals.add(arg.text);
            else if (ts.isTemplateExpression(arg)) {
              const parts = [
                arg.head.text,
                ...arg.templateSpans.map((s) => s.literal.text),
              ];
              if (
                parts.join("").replace(/[^a-z]/gi, "").length >= 10 &&
                parts.length <= 5
              )
                templates.push(parts);
            }
          }
        ts.forEachChild(n, visit);
      }
      visit(source);
    }
  }
}
await scan(new URL("src/", root));
for (const n of [1048576, 16384, 100000, 32767]) {
  literals.add(String(n));
  literals.add(n.toLocaleString("en-US"));
}
await mkdir(new URL("src/generated/", root), { recursive: true });
await writeFile(
  new URL("src/generated/file-error-literals.ts", root),
  `// Generated by build-file-worker.mjs. Only application-owned literal text.\nexport const FILE_ERROR_LITERALS: readonly string[] = ${JSON.stringify([...literals].sort())};\nexport const FILE_ERROR_TEMPLATES: readonly (readonly string[])[] = ${JSON.stringify(templates.sort((a, b) => b.join("").length - a.join("").length))};\n`,
);
const result = await build({
  entryPoints: [new URL("src/workers/file-entry.ts", root).pathname],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
});
await writeFile(
  new URL("src/generated/file-worker-source.ts", root),
  `// Generated by build-file-worker.mjs.\nexport const FILE_WORKER_SOURCE: string = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
console.log(
  `Built isolated file parser (${result.outputFiles[0].contents.length} bytes).`,
);
if (process.argv.includes("--emit-lib"))
  await writeFile(
    new URL("lib/file-worker.js", root),
    result.outputFiles[0].text,
  );
